import sys
import json
import pickle
import requests
import numpy as np
import shap

if sys.platform == "win32":
    sys.stdout.reconfigure(encoding="utf-8")

from confluent_kafka import Consumer, KafkaError
from opentelemetry import propagate, trace
from opentelemetry.sdk.trace import TracerProvider
from opentelemetry.sdk.trace.export import SimpleSpanProcessor, ConsoleSpanExporter

# Initialize OpenTelemetry Tracer
provider = TracerProvider()
processor = SimpleSpanProcessor(ConsoleSpanExporter())
provider.add_span_processor(processor)
trace.set_tracer_provider(provider)
tracer = trace.get_tracer("fluxgate-ai-consumer")


def load_model_and_baseline():
    with open("model.pkl", "rb") as f:
        model = pickle.load(f)
    try:
        with open("baseline_data.pkl", "rb") as f:
            X_train = pickle.load(f)
    except FileNotFoundError:
        # Fallback if baseline_data.pkl does not exist yet (will be generated by train.py)
        X_train = np.random.normal(100, 10, (100, 3))
    return model, X_train


def start_consumer():
    model, X_train = load_model_and_baseline()

    print("Initializing SHAP Explainer...")
    explainer = shap.TreeExplainer(model, data=X_train)
    print("AI Model and SHAP Explainer loaded. Starting Kafka Consumer...")

    # Configure Kafka Consumer
    conf = {
        "bootstrap.servers": "localhost:19092",
        "group.id": "fluxgate-ai-workers",
        "auto.offset.reset": "earliest",
    }

    consumer = Consumer(conf)
    consumer.subscribe(["gateway.traffic.logs"])

    try:
        while True:
            # Poll for new messages every second
            msg = consumer.poll(1.0)

            if msg is None:
                continue

            if msg.error():
                if msg.error().code() == KafkaError._PARTITION_EOF:
                    continue
                else:
                    print(f"Kafka Error: {msg.error()}")
                    break

            # Deserialize tracing context from headers
            headers_dict = {}
            kafka_headers = msg.headers()
            if kafka_headers:
                for k, v in kafka_headers:
                    val = v.decode("utf-8") if isinstance(v, bytes) else v
                    headers_dict[k] = val

            parent_context = propagate.extract(headers_dict)

            # Start Python child span linked to Node.js Gateway span
            with tracer.start_as_current_span("kafka.consume", context=parent_context) as span:
                # Parse JSON
                raw_data = msg.value().decode("utf-8")
                features = json.loads(raw_data)

                # Extract features
                req_size = features.get("requestByteBySize", 0)
                res_size = features.get("responseByteBySize", 0)
                latency = features.get("latencyMs", 0)
                tenant_id = features.get("tenantId")

                span.set_attribute("tenant.id", tenant_id or "")
                span.set_attribute("request.size", req_size)
                span.set_attribute("response.size", res_size)
                span.set_attribute("latency.ms", latency)

                X_test = np.array([[req_size, res_size, latency]])
                score = model.decision_function(X_test)[0]
                prediction = model.predict(X_test)[0]

                if prediction == -1:
                    # Run SHAP explainer to identify anomaly driver
                    shap_values = explainer.shap_values(X_test)

                    # Extract array for single sample
                    if isinstance(shap_values, list):
                        shap_arr = shap_values[0][0]
                    else:
                        shap_arr = shap_values[0]

                    feature_names = ["requestByteSize", "responseByteSize", "latencyMs"]
                    feature_values = [req_size, res_size, latency]

                    abs_shap = np.abs(shap_arr)
                    max_idx = np.argmax(abs_shap)
                    primary_feature = feature_names[max_idx]
                    primary_value = feature_values[max_idx]

                    print(f"ANOMALY! Anomaly driven primarily by {primary_feature} (Value: {primary_value})")

                    requests.post('http://localhost:3000/internal/alerts', json={
                        "tenantId": tenant_id,
                        "alertType": "anomaly_detected",
                        "message": f"Isolation Forest detected abnormal traffic. Driven primarily by {primary_feature} (Value: {primary_value})",
                        "data": { "latencyMs": latency, "requestByteSize": req_size, "primaryFeature": primary_feature, "primaryValue": primary_value }
                    })
                else:
                    print(
                        f"Traffic Normal | "
                        f"Tenant: {tenant_id} | "
                        f"Latency: {latency}ms"
                    )

    except KeyboardInterrupt:
        print("\nShutting down AI worker...")

    finally:
        consumer.close()


if __name__ == "__main__":
    start_consumer()
